-- ---------------------------------------------------------------------------
-- audit_logs - append-only record of important admin actions
-- ---------------------------------------------------------------------------
CREATE TABLE audit_logs (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_id    uuid REFERENCES users (id) ON DELETE SET NULL,
  actor_label text,                  -- snapshot of who acted (survives user deletion)
  action      text NOT NULL,         -- e.g. user.create, profile.delete
  entity_type text,
  entity_id   text,
  summary     text,
  details     jsonb NOT NULL DEFAULT '{}'::jsonb,
  ip          text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX audit_logs_created_idx ON audit_logs (created_at DESC, id DESC);
CREATE INDEX audit_logs_action_idx  ON audit_logs (action, created_at DESC);
CREATE INDEX audit_logs_actor_idx   ON audit_logs (actor_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- rate_limits - shared counter store so limits work across serverless instances
-- ---------------------------------------------------------------------------
CREATE TABLE rate_limits (
  key      text PRIMARY KEY,
  hits     integer NOT NULL DEFAULT 0,
  reset_at timestamptz NOT NULL
);

CREATE INDEX rate_limits_reset_idx ON rate_limits (reset_at);
