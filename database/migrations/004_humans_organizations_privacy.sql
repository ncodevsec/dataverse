-- an organization can no longer own a phonebook: detach it (dropping exact duplicates first so the unique index holds)
DELETE FROM caller_contacts c WHERE c.connection_id IN (SELECT id FROM organizations)
  AND EXISTS (SELECT 1 FROM caller_contacts d WHERE d.connection_id IS NULL AND d.number_digits = c.number_digits AND d.name_key = c.name_key);
UPDATE caller_contacts SET connection_id = NULL WHERE connection_id IN (SELECT id FROM organizations);

