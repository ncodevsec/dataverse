SELECT pp.profile_id, pp.content_type, pp.data, pp.size_bytes, pp.updated_at
  FROM profile_photos pp JOIN organizations o ON o.id = pp.profile_id;

-- ---- connections ---------------------------------------------------------------
-- human -> organization (any link type) and organization -> human (affiliation / connection) become memberships
INSERT INTO memberships (human_id, organization_id, relation, role, started_on, ended_on, note, created_by, created_at, updated_at)
SELECT CASE WHEN h.id IS NOT NULL THEN l.from_id ELSE l.to_id END,
       CASE WHEN h.id IS NOT NULL THEN l.to_id ELSE l.from_id END,
       CASE l.link_type WHEN 'MEMBER_OF' THEN 'MEMBER' WHEN 'AFFILIATED_WITH' THEN 'AFFILIATED' ELSE 'CONNECTED' END,
       l.role, l.started_on, l.ended_on, l.note, l.created_by, l.created_at, l.updated_at
  FROM entity_links l
  LEFT JOIN profiles h ON h.id = l.from_id AND h.entity_type = 'HUMAN'
  JOIN organizations o ON o.id = CASE WHEN h.id IS NOT NULL THEN l.to_id ELSE l.from_id END
 WHERE (h.id IS NOT NULL OR EXISTS (SELECT 1 FROM profiles h2 WHERE h2.id = l.to_id AND h2.entity_type = 'HUMAN'))
   AND l.link_type <> 'SUB_UNIT_OF'
ON CONFLICT DO NOTHING;

INSERT INTO organization_links (from_id, to_id, link_type, role, started_on, ended_on, note, created_by, created_at, updated_at)
SELECT l.from_id, l.to_id, l.link_type, l.role, l.started_on, l.ended_on, l.note, l.created_by, l.created_at, l.updated_at
  FROM entity_links l JOIN organizations a ON a.id = l.from_id JOIN organizations b ON b.id = l.to_id
ON CONFLICT DO NOTHING;

-- whatever is left (human <-> human "connections") is kept, not dropped
CREATE TABLE entity_links_unmapped AS
SELECT l.* FROM entity_links l
 WHERE l.from_id IN (SELECT id FROM profiles WHERE entity_type = 'HUMAN') AND l.to_id IN (SELECT id FROM profiles WHERE entity_type = 'HUMAN');
DO $$ DECLARE n integer; BEGIN
  SELECT count(*) INTO n FROM entity_links_unmapped;
  IF n > 0 THEN RAISE NOTICE '% human-to-human connection(s) were kept in table entity_links_unmapped', n; END IF;
END $$;

