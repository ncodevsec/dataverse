-- 004: separate Human and Organization entities, website field, photo-blur setting
--
--  * `profiles` now holds ONLY humans (ids unchanged, so every "Dataverse ID", family link and marriage keeps working).
--  * Everything that was a non-human profile (group / organization / political party / other / family) moves to the new
--    `organizations` table WITH THE SAME ID, together with its photo, posts, contact numbers and connections.
--  * Family entities are converted to organizations of type GROUP (nothing is deleted).
--  * Human <-> organization connections become `memberships`; organization <-> organization connections become `organization_links`.
--  * Anything that cannot be mapped (a human <-> human "connection") is kept in `entity_links_unmapped`.

-- ---- new tables ------------------------------------------------------------
CREATE TABLE organizations (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_type         text NOT NULL DEFAULT 'ORGANIZATION'
                   CHECK (org_type IN ('COMPANY', 'ORGANIZATION', 'POLITICAL_PARTY', 'GROUP', 'NGO', 'GOVERNMENT', 'EDUCATIONAL', 'OTHER')),
  name             text NOT NULL CHECK (length(btrim(name)) > 0),
  short_name       text,
  email            text,
  phone            text,
  phone_digits     text GENERATED ALWAYS AS (regexp_replace(coalesce(phone, ''), '\D', '', 'g')) STORED,
  website          text,
  founded_on       date,
  dissolved_on     date,
  -- main (registered) address
  street           text,
  union_name       text,
  sub_district     text,
  district         text,
  state            text,
  zip              text,
  country          text,
  -- office / current address
  present_street   text,
  present_city     text,
  social_links     jsonb NOT NULL DEFAULT '{}'::jsonb,
  about            text,
  tags             text[] NOT NULL DEFAULT '{}',
  photo_updated_at timestamptz,        -- logo; bytes live in organization_photos
  created_by       uuid REFERENCES users (id) ON DELETE SET NULL,
  updated_by       uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT organizations_dates CHECK (founded_on IS NULL OR dissolved_on IS NULL OR dissolved_on >= founded_on)
);
CREATE INDEX organizations_type_idx      ON organizations (org_type);
CREATE INDEX organizations_created_idx   ON organizations (created_at DESC, id DESC);
CREATE INDEX organizations_name_sort_idx ON organizations (lower(name), id);
CREATE INDEX organizations_name_trgm_idx ON organizations USING gin (name gin_trgm_ops);
CREATE INDEX organizations_tags_idx      ON organizations USING gin (tags);
CREATE TRIGGER organizations_set_updated_at BEFORE UPDATE ON organizations FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE organization_photos (
  organization_id integer PRIMARY KEY REFERENCES organizations (id) ON DELETE CASCADE,
  content_type    text NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
  data            bytea NOT NULL,
  size_bytes      integer NOT NULL,
  updated_at      timestamptz NOT NULL DEFAULT now()
);

-- a human's membership / affiliation / connection with an organization (independent of family relationships)
CREATE TABLE memberships (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  human_id        integer NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
  organization_id integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  relation        text NOT NULL DEFAULT 'MEMBER' CHECK (relation IN ('MEMBER', 'AFFILIATED', 'CONNECTED')),
  role            text,
  started_on      date,
  ended_on        date,
  note            text,
  created_by      uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT memberships_dates CHECK (started_on IS NULL OR ended_on IS NULL OR ended_on >= started_on)
);
CREATE UNIQUE INDEX memberships_unique_key ON memberships (human_id, organization_id, relation);
CREATE INDEX memberships_org_idx ON memberships (organization_id, relation);
CREATE TRIGGER memberships_set_updated_at BEFORE UPDATE ON memberships FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- organization <-> organization (sub-units, membership of a federation/party, affiliation, connection)
CREATE TABLE organization_links (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_id    integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  to_id      integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  link_type  text NOT NULL CHECK (link_type IN ('SUB_UNIT_OF', 'MEMBER_OF', 'AFFILIATED_WITH', 'CONNECTED_TO')),
  role       text,
  started_on date,
  ended_on   date,
  note       text,
  created_by uuid REFERENCES users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT organization_links_not_self CHECK (from_id <> to_id),
  CONSTRAINT organization_links_dates    CHECK (started_on IS NULL OR ended_on IS NULL OR ended_on >= started_on)
);
CREATE UNIQUE INDEX organization_links_unique_key ON organization_links (from_id, to_id, link_type);
CREATE INDEX organization_links_to_idx ON organization_links (to_id, link_type);
CREATE TRIGGER organization_links_set_updated_at BEFORE UPDATE ON organization_links FOR EACH ROW EXECUTE FUNCTION set_updated_at();

